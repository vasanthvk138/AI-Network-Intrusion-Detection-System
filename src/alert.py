# =========================
# 🚨 SEVERITY LEVEL
# =========================
def get_severity(attack):

    severity = {

        "PortScan": "MEDIUM",
        "DDoS": "CRITICAL",
        "BruteForce": "HIGH",
        "BENIGN": "LOW"
    }

    return severity.get(attack, "HIGH")


# =========================
# 📧 SEND ALERT EMAIL
# =========================
def send_alert(ip, attack):

    try:

        # =========================
        # EMAIL OBJECT
        # =========================
        msg = MIMEMultipart()

        msg['From'] = EMAIL
        msg['To'] = RECEIVER
        msg['Subject'] = (
            f"🚨 IDS ALERT — {attack} Detected"
        )

        # =========================
        # ALERT DETAILS
        # =========================
        severity = get_severity(attack)

        solution = get_solution(attack)

        current_time = datetime.now().strftime(
            "%Y-%m-%d %H:%M:%S"
        )

        # =========================
        # EMAIL BODY
        # =========================
        body = f"""
==================================================
        AI INTRUSION DETECTION SYSTEM
==================================================

🚨 SECURITY ALERT GENERATED

Attack Type :
{attack}

Attacker IP :
{ip}

Timestamp :
{current_time}

Severity :
{severity}

==================================================
🛡️ RECOMMENDED MITIGATION
==================================================

{solution}

==================================================
⚠️ ACTION REQUIRED
==================================================

Please investigate this activity immediately.

This alert was automatically generated by
your AI Network Intrusion Detection System.

==================================================
"""

        # =========================
        # ATTACH BODY
        # =========================
        msg.attach(
            MIMEText(body, 'plain')
        )

        # =========================
        # SMTP SERVER
        # =========================
        server = smtplib.SMTP(
            'smtp.gmail.com',
            587
        )

        server.starttls()

        # =========================
        # LOGIN
        # =========================
        server.login(
            EMAIL,
            PASSWORD
        )

        # =========================
        # SEND EMAIL
        # =========================
        server.send_message(msg)

        server.quit()

        print(
            f"📧 Email alert sent successfully for {attack}"
        )

    except Exception as e:

        print("❌ Email error:", e)